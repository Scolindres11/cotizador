  lote            text,
  total           numeric,
  creado_por      text,
  creado_en       timestamptz not null default now()
);
create index if not exists ordenes_compra_org_idx on public.ordenes_compra (organizacion_id);

-- ------------------------------------------------- Permisos por correo
create or replace function public.es_autorizado()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.usuarios where lower(email) = lower(auth.jwt() ->> 'email'))
$$;

create or replace function public.es_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.usuarios where lower(email) = lower(auth.jwt() ->> 'email') and rol = 'admin')
$$;

alter table public.usuarios       enable row level security;
alter table public.organizaciones enable row level security;
alter table public.catalogo       enable row level security;
alter table public.cotizaciones   enable row level security;
alter table public.ordenes_compra enable row level security;

do $$
declare t text;
begin
  -- usuarios, organizaciones y catálogo: leen autorizados, editan admin
  foreach t in array array['usuarios', 'organizaciones', 'catalogo'] loop
    execute format('drop policy if exists "leer autorizados" on public.%I', t);
    execute format('drop policy if exists "editar admin" on public.%I', t);
    execute format('create policy "leer autorizados" on public.%I for select to authenticated using (public.es_autorizado())', t);
    execute format('create policy "editar admin" on public.%I for all to authenticated using (public.es_admin()) with check (public.es_admin())', t);
  end loop;
end $$;

-- cotizaciones: todos los autorizados leen y editan
drop policy if exists "autorizados" on public.cotizaciones;
create policy "autorizados" on public.cotizaciones for all to authenticated
  using (public.es_autorizado()) with check (public.es_autorizado());

drop policy if exists "leer autorizados" on public.ordenes_compra;
create policy "leer autorizados" on public.ordenes_compra for select to authenticated using (public.es_autorizado());

revoke all on public.usuarios, public.organizaciones, public.catalogo, public.cotizaciones, public.ordenes_compra from anon;
grant select, insert, update, delete on public.usuarios, public.organizaciones, public.catalogo, public.cotizaciones to authenticated;
grant select on public.ordenes_compra to authenticated;

-- ------------------------------------------------------------ Funciones
-- Búsqueda en el catálogo: sin importar tildes ni mayúsculas, 60 resultados
create or replace function public.buscar_catalogo(q text)
returns setof public.catalogo
language sql stable security invoker set search_path = public, extensions as $$
  select c.*
    from public.catalogo c
   where c.busqueda like all (
           array(select '%' || w || '%'
                   from unnest(regexp_split_to_array(public.normalizar(trim(q)), '\s+')) w
                  where w <> ''))
   order by (c.precio is null), similarity(c.busqueda, public.normalizar(q)) desc, c.producto
   limit 60
$$;

create or replace function public.crear_orden_compra(
  p_organizacion_id text, p_organizacion text, p_lote text, p_total numeric
) returns public.ordenes_compra
language plpgsql security definer set search_path = public as $$
declare r public.ordenes_compra;
begin
  if not public.es_autorizado() then raise exception 'Tu correo no está autorizado'; end if;
  insert into public.ordenes_compra (numero, organizacion_id, organizacion, lote, total, creado_por)
  values ('OC-' || lpad(nextval('public.ordenes_compra_seq')::text, 3, '0'),
          p_organizacion_id, p_organizacion, p_lote, p_total, auth.jwt() ->> 'email')
  returning * into r;
  return r;
end $$;

create or replace function public.vaciar_catalogo()
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.es_admin() then raise exception 'Solo la administradora puede vaciar el catálogo'; end if;
  truncate table public.catalogo;
end $$;

revoke all on function public.es_autorizado(), public.es_admin(), public.buscar_catalogo(text),
  public.crear_orden_compra(text, text, text, numeric), public.vaciar_catalogo() from public, anon;
grant execute on function public.es_autorizado(), public.es_admin(), public.buscar_catalogo(text),
  public.crear_orden_compra(text, text, text, numeric), public.vaciar_catalogo() to authenticated;

