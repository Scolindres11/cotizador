create table if not exists public.catalogo (
  id                bigint generated by default as identity primary key,
  tienda            text,
  producto          text not null,
  precio            numeric,
  enlace            text,
  especificacion    text,
  motivo_sin_precio text,
  busqueda          text generated always as
                    (public.normalizar(coalesce(producto, '') || ' ' || coalesce(tienda, '') || ' ' || coalesce(especificacion, ''))) stored
);
create index if not exists catalogo_busqueda_trgm on public.catalogo using gin (busqueda extensions.gin_trgm_ops);

create table if not exists public.cotizaciones (
  id                bigint generated by default as identity primary key,
  fuente            text not null check (fuente in ('COMRURAL', 'Aporte GP')),
  lote              text,
  organizacion      text,
  organizacion_id   bigint references public.organizaciones(id) on delete set null,
  item_buscado      text,
  cantidad          numeric,
  unidad            text,
  producto          text,
  tienda            text,
  precio_unit       numeric,
  enlace            text,
  observaciones     text,
  especificacion    text,
  motivo_sin_precio text,
  comprar           boolean not null default false,
  subtotal          numeric generated always as (cantidad * precio_unit) stored,
  es_manual         boolean not null default false,
  pasado_catalogo   boolean not null default false,
  creado_por        text default (auth.jwt() ->> 'email'),
  creado_en         timestamptz not null default now()
